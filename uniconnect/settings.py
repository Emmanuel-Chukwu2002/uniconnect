# Other providers also need EMAIL_HOST / EMAIL_PORT (defaults: smtp.gmail.com,
# 587 with TLS; EMAIL_PORT=465 switches to SSL). Without EMAIL_HOST_USER, emails are printed in the terminal
# that runs the server instead.
