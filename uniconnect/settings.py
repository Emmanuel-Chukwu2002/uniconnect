def _load_env_file(path):
    """Reads KEY=value lines from the project's .env file into the
    environment (without overriding anything already set). Keeps
    secrets such as the ImageKit private key out of the code."""
    import os
    if not path.exists():
        return
    # utf-8-sig: also accepts a .env that Notepad/PowerShell saved with a BOM.
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


_load_env_file(BASE_DIR / '.env')


