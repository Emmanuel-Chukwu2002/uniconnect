EMAIL_USE_SSL = _os.environ.get('EMAIL_USE_SSL', '1' if EMAIL_PORT == 465 else '') == '1'
EMAIL_USE_TLS = not EMAIL_USE_SSL and _os.environ.get('EMAIL_USE_TLS', '1') == '1'
