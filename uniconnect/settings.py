# Database. PostgreSQL once DB_NAME is in the .env file next to manage.py:
#   DB_NAME=uniconnect
#   DB_USER=uniconnect_user
#   DB_PASSWORD=your-password
#   DB_HOST=localhost        (optional, this is the default)
#   DB_PORT=5432             (optional, this is the default)
# Without DB_NAME it keeps using the SQLite file db.sqlite3, as before.
# The old SQLite file stays reachable as the "sqlite" database, so
# `python manage.py move_to_postgres` can copy everything across once.
import os as _dbos
_SQLITE = {'ENGINE': 'django.db.backends.sqlite3', 'NAME': BASE_DIR / 'db.sqlite3'}
if _dbos.environ.get('DATABASE_URL'):
    # Online: Render (and most hosts) give one DATABASE_URL, postgresql://user:password@host:port/name
    from urllib.parse import unquote, urlparse
    _u = urlparse(_dbos.environ['DATABASE_URL'])
    DATABASES = {'default': {
        'ENGINE': 'django.db.backends.postgresql', 'NAME': _u.path.lstrip('/'),
        'USER': unquote(_u.username or ''), 'PASSWORD': unquote(_u.password or ''),
        'HOST': _u.hostname or 'localhost', 'PORT': str(_u.port or 5432), 'CONN_MAX_AGE': 60,
    }}
elif _dbos.environ.get('DB_NAME'):
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': _dbos.environ['DB_NAME'],
            'USER': _dbos.environ.get('DB_USER', 'postgres'),
            'PASSWORD': _dbos.environ.get('DB_PASSWORD', ''),
            'HOST': _dbos.environ.get('DB_HOST', 'localhost'),
            'PORT': _dbos.environ.get('DB_PORT', '5432'),
            'CONN_MAX_AGE': 60,
        },
        'sqlite': _SQLITE,
    }
else:
    DATABASES = {'default': _SQLITE}


